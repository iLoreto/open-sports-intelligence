/** Reproducible offline artifact: past seasons train Elo, following season is held out. */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { carryoverRatings, ELO_SETTINGS, replaySeason, scorePredictions } from './worker/elo.ts';

const ESPN = 'https://site.api.espn.com/apis/site/v2/sports/basketball/nba/scoreboard';
const SEASONS = [2024, 2025, 2026];
const MONTHS = [10, 11, 12, 1, 2, 3, 4];

async function fetchMonth(season, month) {
  const calendarYear = month >= 10 ? season - 1 : season;
  const key = `${calendarYear}${String(month).padStart(2, '0')}`;
  const url = `${ESPN}?dates=${key}&limit=500`;
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const response = await fetch(url, { signal: AbortSignal.timeout(20000) });
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      const json = await response.json();
      if (!Array.isArray(json.events)) throw new Error('No events array');
      return { key, events: json.events };
    } catch (error) {
      if (attempt === 3) throw new Error(`ESPN month ${key} failed: ${error.message}`);
      await new Promise((resolve) => setTimeout(resolve, 1000 * attempt));
    }
  }
}

function completedGame(event, season) {
  if (event.season?.type !== 2 || event.season?.year !== season || !event.id || !event.date) return null;
  const competition = event.competitions?.[0];
  // NBA Cup final (CC) and All-Star events can carry ESPN season.type=2.
  // STD is the normal 82-game regular-season schedule, including Cup group games.
  if (competition?.type?.abbreviation !== 'STD') return null;
  if (!event.status?.type?.completed && !competition?.status?.type?.completed) return null;
  const home = competition?.competitors?.find((c) => c.homeAway === 'home');
  const away = competition?.competitors?.find((c) => c.homeAway === 'away');
  const homeScore = Number(home?.score);
  const awayScore = Number(away?.score);
  if (!home?.team?.id || !away?.team?.id || !Number.isFinite(homeScore) || !Number.isFinite(awayScore)) return null;
  return { id: event.id, date: event.date, season, homeId: home.team.id, awayId: away.team.id, homeScore, awayScore };
}

async function main() {
  const tasks = SEASONS.flatMap((season) => MONTHS.map((month) => ({ season, month })));
  const results = [];
  // Limit upstream concurrency; fail closed if any month is unavailable.
  for (let index = 0; index < tasks.length; index += 4) {
    const group = await Promise.all(tasks.slice(index, index + 4).map(async ({ season, month }) => ({ season, ...await fetchMonth(season, month) })));
    results.push(...group);
    console.log(`Retrieved ${results.length}/${tasks.length} historical NBA months`);
  }

  const all = new Map();
  for (const { season, events } of results) for (const event of events) {
    const game = completedGame(event, season);
    if (game) all.set(game.id, game);
  }
  const gameCounts = Object.fromEntries(SEASONS.map((season) => [season, [...all.values()].filter((game) => game.season === season).length]));
  for (const [season, count] of Object.entries(gameCounts)) {
    if (count !== 1230) throw new Error(`Expected exactly 1,230 regular-season games for ${season}, found ${count}. No model artifact was written.`);
  }

  let ratings = {};
  const trainPredictions = [];
  let validation = [];
  for (const season of SEASONS) {
    if (season !== SEASONS[0]) ratings = carryoverRatings(ratings);
    const seasonGames = [...all.values()].filter((game) => game.season === season);
    const evaluated = replaySeason(seasonGames, ratings);
    ratings = evaluated.ratings;
    if (season === 2026) validation = evaluated.evaluated;
    else trainPredictions.push(...evaluated.evaluated);
  }

  const baselineHomeProbability = trainPredictions.reduce((sum, row) => sum + row.homeWon, 0) / trainPredictions.length;
  const score = scorePredictions(validation, baselineHomeProbability);
  const artifact = {
    model: 'NBA Elo baseline v1', trainedThroughSeason: 2026, forecastSeason: 2027,
    generatedAt: new Date().toISOString(),
    source: 'ESPN public NBA scoreboards, completed regular-season games only',
    trainingSeasons: [2024, 2025], validationSeason: 2026,
    trainingGames: trainPredictions.length, perSeasonGames: gameCounts,
    settings: ELO_SETTINGS, baselineHomeProbability, validation: score,
    initialRatings: carryoverRatings(ratings)
  };
  const target = fileURLToPath(new URL('./worker/nba-baseline.ts', import.meta.url));
  await writeFile(target, `/** GENERATED by build-nba-baseline.mjs. Run the script to reproduce. */\nexport const nbaBaseline = ${JSON.stringify(artifact, null, 2)} as const;\n`);
  console.log(JSON.stringify({ target, gameCounts, validation: score, baselineHomeProbability }, null, 2));
}

await main();
